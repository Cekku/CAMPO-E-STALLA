// Utilità generali: formattazione, date, escape
export const $ = (s, r = document) => r.querySelector(s);
export const $$ = (s, r = document) => [...r.querySelectorAll(s)];
export const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
export const N = v => { if (v === null || v === undefined || v === '') return 0; const n = parseFloat(String(v).replace(',', '.')); return isFinite(n) ? n : 0; };
export const has = v => v !== null && v !== undefined && v !== '';
export const nf = (v, d = 1) => Number(v || 0).toLocaleString('it-IT', { maximumFractionDigits: d });
export const eur = (v, d = 0) => Number(v || 0).toLocaleString('it-IT', { style: 'currency', currency: 'EUR', maximumFractionDigits: d, minimumFractionDigits: d });
export const isoOf = d => d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0');
export const today = () => isoOf(new Date());
export const okD = s => typeof s === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(s);
const utc = s => { const [y, m, d] = s.split('-').map(Number); return Date.UTC(y, m - 1, d); };
export const addDays = (s, n) => new Date(utc(s) + n * 864e5).toISOString().slice(0, 10);
export const diff = (a, b) => Math.round((utc(b) - utc(a)) / 864e5);
export const fd = s => { if (!okD(s)) return '—'; const [y, m, d] = s.split('-'); return d + '/' + m + '/' + y.slice(2); };
const MESI = ['gen', 'feb', 'mar', 'apr', 'mag', 'giu', 'lug', 'ago', 'set', 'ott', 'nov', 'dic'];
const GIORNI = ['dom', 'lun', 'mar', 'mer', 'gio', 'ven', 'sab'];
export const fdLong = s => { if (!okD(s)) return '—'; const [y, m, d] = s.split('-').map(Number); return d + ' ' + MESI[m - 1] + ' ' + y; };
export const fdShort = s => { if (!okD(s)) return '—'; const [, m, d] = s.split('-').map(Number); return d + ' ' + MESI[m - 1]; };
export const weekday = s => GIORNI[new Date(utc(s)).getUTCDay()];
export const yearOf = s => okD(s) ? Number(s.slice(0, 4)) : null;
export const sum = (a, f) => a.reduce((t, x) => t + N(f(x)), 0);
export const byDate = (a, b) => (a.data || '').localeCompare(b.data || '');
export const byName = (a, b) => (a.nome || a.matricola || '').localeCompare(b.nome || b.matricola || '', 'it');
export const eta = s => { if (!okD(s)) return ''; const m = Math.floor(diff(s, today()) / 30.44); return m < 24 ? m + ' mesi' : Math.floor(m / 12) + ' anni'; };
export const uid = () => (crypto.randomUUID ? crypto.randomUUID() : 'x' + Date.now().toString(36) + Math.random().toString(36).slice(2));
export const debounce = (fn, ms) => { let t; return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); }; };
export const lsGet = (k, d = null) => { try { const v = localStorage.getItem(k); return v === null ? d : JSON.parse(v); } catch (e) { return d; } };
export const lsSet = (k, v) => { try { localStorage.setItem(k, JSON.stringify(v)); } catch (e) { } };
export const plural = (n, s, p) => n + ' ' + (n === 1 ? s : p);
